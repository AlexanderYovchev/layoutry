import { getDocumentDefaultStyle, type CssDeclaration } from "@/features/canvas";
import type { ExportDocument, ExportElement } from "@/features/export/types/exportIr";
import { exportBaseStylesheet } from "@/features/export/utils/exportBaseStylesheet";
import { defaultStyleClassName, elementStyleClassName } from "@/features/export/utils/exportClassNames";

function rule(selector: string, declarations: readonly CssDeclaration[], indent = ""): string {
  const body = declarations.map(([property, value]) => `${indent}  ${property}: ${value};`).join("\n");
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

function collectElementRules(element: ExportElement, rules: string[]) {
  if (element.declarations.length > 0) rules.push(rule(`.${elementStyleClassName(element)}`, element.declarations));
  for (const child of element.children) if (child.kind === "element") collectElementRules(child, rules);
}

/**
 * The complete stylesheet for an exported page (EXPORT-1.2), in cascade
 * order: the base reset and page surface, then the default presentations
 * the page actually uses (in their shared table order), then each
 * element's own authored rule in document order. Defaults precede element
 * rules at equal specificity, so authored styles always win — exactly as
 * the Canvas's inline styles win over its default classes.
 */
export function printExportStylesheet(document: ExportDocument): string {
  const sections: string[] = ["/* Generated by Layoutry — HTML/CSS export. */", exportBaseStylesheet(getDocumentDefaultStyle("page-surface").declarations)];

  for (const id of document.defaultStyles) {
    const entry = getDocumentDefaultStyle(id);
    const selector = `.${defaultStyleClassName(id)}`;
    sections.push(rule(selector, entry.declarations));
    if (entry.media) sections.push(`@media ${entry.media.query} {\n${rule(selector, entry.media.declarations, "  ")}\n}`);
    if (entry.backdrop) sections.push(rule(`${selector}::backdrop`, entry.backdrop));
  }

  const elementRules: string[] = [];
  collectElementRules(document.root, elementRules);
  sections.push(...elementRules);

  return `${sections.join("\n\n")}\n`;
}
